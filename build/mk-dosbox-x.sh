#!/usr/bin/env bash
#
# mk-dosbox-x.sh — build DOSBox-X for i686, because the DOS emulator Void ships
# cannot run on the hardware this distribution targets.
#
# ⛔ dosbox-staging CANNOT EXECUTE ON A PENTIUM 4, AND NO CONFIGURATION FIXES IT.
# Measured on the reference machine: `objdump -d /usr/bin/dosbox` on Void's
# dosbox-staging 0.82.2 contains **19 `pshufb`** instructions. pshufb is SSSE3,
# introduced with Core 2, and it has no legacy encoding to fall back to. The
# Pentium 4 reports:
#
#     flags: mmx sse sse2 pni          (pni is SSE3, and that is the ceiling)
#
# so it faults on sight — SIGILL inside GFX_Events, every launch. Void sets no
# arch flags; the baseline comes from upstream's own build. It is not velle's
# config, not nouveau, and not the X server: it fails identically under nouveau,
# llvmpipe and NVIDIA 304.
#
# ⚠ There is a SECOND, unrelated bug that this replaces rather than fixes:
# SDL2 on this machine cannot match a GLX visual ("Couldn't find matching GLX
# visual") even though the server offers 192 of them, on all three GL stacks.
# `SDL_VIDEO_X11_VISUALID=0x021` works around it. DOSBox-X does not hit it.
#
# ── Why DOSBox-X and not plain dosbox ───────────────────────────────────────
#
# Void's dosbox 0.74pl3 also runs (0 problematic instructions) and is a fine
# fallback, but it is the 2010 original. DOSBox-X is the accuracy-focused fork,
# it is what velle prefers, and it is clean on this CPU: `lzcnt` x22 and `tzcnt`
# x2 and nothing else, both of which DECODE AS bsr/bsf on a pre-ABM CPU rather
# than faulting. Fatal-instruction count: zero.
#
# ── Two things its build needs that are not obvious ─────────────────────────
#
# ⛔ IT REQUIRES ITS OWN PATCHED SDL. Building against Void's SDL 1.2 fails on
# `SDLK_JP_RO`, `SDLK_JP_YEN`, `SDLK_KP_COMMA` and a deliberate #error saying so
# in as many words. Upstream ships no build-sdl1 for Linux any more, so this
# uses their build-sdl2, which is the supported path.
#
# ⛔ AND -msse2, OR IT DOES NOT COMPILE. render.cpp uses SSE2 intrinsics
# (_mm_movemask_epi8, _mm_loadu_si128) and i686's baseline does not enable them:
# "inlining failed in call to always_inline ... target specific option mismatch".
# ⚠ That makes the binary require SSE2, which is BELOW Void's generic i686 but
# fine here — this project's stated target is "Pentium 4 and later 32-bit x86",
# and every such CPU has SSE2. It would not run on a Pentium III.
#
#     build/mk-dosbox-x.sh
#
# ⚠ ~30 minutes; the source tarball alone is 127 MB.
#
# SPDX-License-Identifier: GPL-2.0-or-later
set -euo pipefail
cd "$(dirname "$0")/.."
. build/config.sh

SRCPKG=dosbox-x
VER=2026.08.31
ARCH=i686
OUT="out/${EMBER_ID}-repo-$ARCH"
WORK="out/kernel-build"          # the checkout mk-kernel/mk-thunar/mk-mesa share
IMAGE="ghcr.io/void-linux/void-linux:latest-full-$ARCH"

echo "== $SRCPKG $VER -> $OUT"

NEED_GB=8
FREE_GB=$(df -BG --output=avail . | tail -1 | tr -dc '0-9')
[ "${FREE_GB:-0}" -ge "$NEED_GB" ] || {
    echo "mk-dosbox-x: needs ~${NEED_GB}G free, have ${FREE_GB}G" >&2; exit 1; }

mkdir -p "$OUT" "$WORK"
[ -d "$WORK/void-packages/.git" ] || {
    echo "   clone   void-packages (shallow)"
    git clone --depth 1 https://github.com/void-linux/void-packages "$WORK/void-packages"; }

# ⚠ Void does not package DOSBox-X at all — only dosbox and dosbox-staging — so
# this writes a template rather than patching one. It lives in the shared
# checkout and is regenerated every run, so editing it there is pointless.
SRCDIR="$WORK/void-packages/srcpkgs/$SRCPKG"
mkdir -p "$SRCDIR"
cat > "$SRCDIR/template" <<TEMPLATE
# Template file for '$SRCPKG'
# GENERATED BY build/mk-dosbox-x.sh — edit that, not this.
pkgname=$SRCPKG
version=$VER
revision=1
wrksrc="dosbox-x-dosbox-x-v\${version}"
build_style=gnu-configure
# ⛔ --enable-sdl2 IS NOT OPTIONAL. configure looks for SDL 1.x by default and
# stops with "SDL 1.x or SDL 2.x is required to compile this program" even with
# SDL2-devel installed. Upstream's build-sdl2 passes it; it also passes
# --enable-debug, which is deliberately NOT carried over here — that is what
# makes their binary 21 MB.
configure_args="--enable-core-inline --enable-sdl2"
hostmakedepends="pkg-config automake autoconf libtool nasm"
makedepends="SDL2-devel SDL2_net-devel libpng-devel zlib-devel alsa-lib-devel
 libX11-devel libXrandr-devel libXext-devel fluidsynth-devel libslirp-devel
 freetype-devel ffmpeg6-devel"
short_desc="DOS emulator focused on accuracy, for hardware of the era"
maintainer="Ember <ember@localhost>"
license="GPL-2.0-or-later"
homepage="https://dosbox-x.com"
distfiles="https://github.com/joncampbell123/dosbox-x/archive/refs/tags/dosbox-x-v\${version}.tar.gz"
checksum=992ea538ea858f9fb196b39de2276ce3048c731965e144e6288202abed109782

# ⛔ SSE2 or it does not compile — see build/mk-dosbox-x.sh for why, and for why
# that is acceptable on this target and would not be on a Pentium III.
CFLAGS="-msse2"
CXXFLAGS="-msse2"

pre_configure() {
	./autogen.sh
}
TEMPLATE
echo "   template written"

echo "   build   ~30 minutes"
docker run --rm --privileged \
    -v "$PWD/$WORK/void-packages:/void-packages" \
    -v "$PWD/$OUT:/out" \
    "$IMAGE" \
    /bin/sh -euc "
        xbps-install -Sy xbps >/dev/null 2>&1 || true
        xbps-install -Sy bash shadow git >/dev/null
        rm -f /void-packages/etc/conf
        id -u 1000 >/dev/null 2>&1 || useradd -m -u 1000 -s /bin/bash builder
        BU=\$(id -nu 1000)
        chown \$BU /void-packages /out
        su \$BU -c 'cd /void-packages && ./xbps-src binary-bootstrap && ./xbps-src -j'\$(nproc)' pkg $SRCPKG'
        find /void-packages/hostdir/binpkgs -name '$SRCPKG-*.i686.xbps' ! -name '*-dbg-*' \
             -exec cp -v {} /out/ \;
    "

echo "   index   rebuilding repository metadata"
docker run --rm -v "$PWD/$OUT:/out" "$IMAGE" \
    /bin/sh -euc "xbps-rindex -a /out/*.xbps"

echo "== done"
ls -1 "$OUT"/${SRCPKG}-*.xbps 2>/dev/null | sed 's/^/   /'
